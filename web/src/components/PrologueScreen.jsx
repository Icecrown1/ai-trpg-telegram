export default function PrologueScreen({ busy, onDone }) {
  const [step, setStep] = useState(0)
  const [lead, setLead] = useState(null)
  const s = STEPS[step]
  const last = step === STEPS.length - 1
  const text = (lead ? lead + '\n\n' : '') + s.text

  return (
    <div className="screen">
      <div className="panel log-outer">
        <span className="panel-title">The Last King · пролог</span>
        <div className="log-scroll">
          {s.art && <SceneArt tag={s.art} />}
          <div className="log-entry">
            <div className="log-narration">{text}</div>
          </div>
        </div>
      </div>

      <div className="actions">
        {!last && s.actions.map((a) => (
          <button key={a.t} disabled={busy}
            onClick={() => { setLead(a.lead); setStep(step + 1) }}>{a.t}</button>
        ))}
        {last && (
          <button className="primary" disabled={busy} onClick={onDone}>
            ▸ ПРИНЯТЬ ПЕРВОГО ИСКАТЕЛЯ
          </button>
        )}
      </div>

      <button className="muted" style={{ border: 'none', alignSelf: 'center', fontSize: 12 }}
        disabled={busy} onClick={onDone}>
        пропустить пролог
      </button>
    </div>
  )
}
