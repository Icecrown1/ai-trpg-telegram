def depth_bonus(depth: int, creature: dict) -> int:
    """Глубже — матёрее: +1 к защите с 4-й глубины, +2 с 6-й. Боссы живут по своим правилам."""
    if creature.get("boss"):
        return 0
    d = int(depth or 1)
    return 2 if d >= 6 else 1 if d >= 4 else 0


def get(cid: str | None) -> dict | None:
    return CREATURES.get(cid) if cid else None


def for_dungeon(dungeon_id: str) -> dict:
    return {cid: c for cid, c in CREATURES.items()
            if "*" in c["dungeons"] or dungeon_id in c["dungeons"]}


def prompt_block(dungeon_id: str) -> str:
    rows = [
        f"- {cid}: {c['name']} — КД {c['ac']}, HP {c['hp']}, атака +{c['atk']}, урон {c['dmg']} ({c['why']})"
        for cid, c in for_dungeon(dungeon_id).items()
    ]
    return (
        "БЕСТИАРИЙ ЭТОГО ПОДЗЕМЕЛЬЯ (КД — сложность попасть по существу; сервер подставит её сам):\n"
        + "\n".join(rows)
        + "\n- Атакуя известное существо, передай в roll_dice target=<id>: сервер поставит КД (с поправкой за глубину). "
        "Удар существа по игроку — attacker=<id>: сервер добавит его бонус атаки. Урон существ бросай по их кубику."
        "\n- Здоровье веди честно по таблице: раненый слабеет, убитый не встаёт."
        "\n- Существо не из таблицы — назначь КД по логике, сравнив с похожим: без брони 10-11, ловкое или в коже 12, "
        "панцирь или кольчуга 14-15, камень и латы 16+, крошечное и мерцающее 16. Тогда передай dc сам."
    )
